import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { parseArgs } from 'node:util';
import { checkInjectLists, formatDiagnostic as format, type Diagnostic } from './check.js';
import { generateClient, sameContent } from './client.js';
import { writeManifest } from './manifest.js';
import { INJECT_HEADER, generateInjects, plural } from './inject.js';
import { GENERATED, watchProject, type WatchProjectOptions } from './watch.js';

const USAGE = `Usage:
  avi-compile check [--project tsconfig.json]
      Type-check every static inject list against its constructor.
  avi-compile manifest <entry.js> [--export AppModule] [--out avi.manifest.json]
      Describe the app's modules, providers and routes without starting it.
  avi-compile client [--project tsconfig.json] [--out src/api.gen.ts] [--root file.ts#AppModule] [--check | --watch]
      Generate the Api type for @avijs/client. --check fails if the file is out of date;
      --watch updates it whenever routes change.
  avi-compile inject [--project tsconfig.json] [--out src/inject.gen.ts] [--check | --watch]
      Infer dependency lists from constructor types, for classes without static inject.`;

export async function main(argv: readonly string[]): Promise<number> {
  const [command, ...rest] = argv;
  const { values, positionals } = parseArgs({
    args: [...rest],
    allowPositionals: true,
    options: {
      project: { type: 'string', default: 'tsconfig.json' },
      export: { type: 'string', default: 'AppModule' },
      out: { type: 'string' },
      root: { type: 'string' },
      check: { type: 'boolean', default: false },
      watch: { type: 'boolean', default: false },
    },
  });

  if (command === 'check') {
    const diagnostics = checkInjectLists(values.project);
    for (const d of diagnostics) console.log(format(d));
    const errors = diagnostics.filter((d) => d.severity === 'error').length;
    console.log(
      `${String(errors)} error(s), ${String(diagnostics.length - errors)} warning(s) in static inject lists`,
    );
    return errors > 0 ? 1 : 0;
  }

  if (command === 'client') {
    const out = values.out ?? inProject(values.project, 'src/api.gen.ts');
    if (values.watch)
      return watch({ project: values.project, client: { out, root: values.root } }, out);
    const result = generateClient({ project: values.project, out, root: values.root });
    const summary = `${String(result.routes.length)} routes`;
    return once({ ...result, summary }, out, GENERATED, 'avi client', values.check);
  }
  if (command === 'inject') {
    const out = values.out ?? inProject(values.project, 'src/inject.gen.ts');
    if (values.watch) return watch({ project: values.project, inject: { out } }, out);
    const result = generateInjects({ project: values.project, out });
    const summary = plural(result.classes.length, 'dependency list');
    return once({ ...result, summary }, out, INJECT_HEADER, 'avi inject', values.check);
  }

  if (command === 'manifest' && positionals[0]) {
    const out = values.out ?? 'avi.manifest.json';
    const description = await writeManifest({
      entry: positionals[0],
      exportName: values.export,
      out,
    });
    console.log(
      `Wrote ${out}: ${String(description.modules.length)} modules, ${String(description.routes.length)} routes`,
    );
    for (const controller of description.dynamic) {
      console.log(`note: ${controller} creates its routes at runtime; they are not listed`);
    }
    return 0;
  }

  console.error(USAGE);
  return 2;
}

/** A path next to the tsconfig.json, as avi dev and avi build resolve it. */
function inProject(project: string, file: string): string {
  return path.posix.join(path.dirname(project).replaceAll('\\', '/'), file);
}

interface Generated {
  readonly source: string;
  readonly diagnostics: readonly Diagnostic[];
  readonly summary: string;
}

/** Writes, or with `check` compares, one generated file. */
async function once(
  result: Generated,
  out: string,
  header: string,
  command: string,
  check: boolean,
): Promise<number> {
  for (const d of result.diagnostics) console.log(format(d));
  if (result.diagnostics.some((d) => d.severity === 'error')) return 1;

  const current = await readFile(out, 'utf8').catch(() => undefined);
  if (check) {
    const same = current !== undefined && sameContent(current, result.source);
    console.log(
      same ? `${out} is up to date (${result.summary})` : `${out} is out of date: run ${command}`,
    );
    return same ? 0 : 1;
  }
  // A mistyped --out must not replace source code.
  if (current !== undefined && !current.startsWith(header)) {
    console.log(`${out}: not written: the file exists and was not generated by avi`);
    return 1;
  }
  await mkdir(path.dirname(path.resolve(out)), { recursive: true });
  await writeFile(out, result.source);
  console.log(`Wrote ${out}: ${result.summary}`);
  return 0;
}

function watch(options: WatchProjectOptions, out: string): Promise<number> {
  const watcher = watchProject({ ...options, emit: false });
  console.log(`Watching for changes; ${out} updates on save`);
  return new Promise((resolve) => {
    const stop = () => {
      watcher.close();
      resolve(0);
    };
    process.once('SIGINT', stop);
    process.once('SIGTERM', stop);
  });
}
