import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import ts from 'typescript';
import { formatDiagnostic, type Diagnostic } from './check.js';
import { generateFrom, sameContent } from './client.js';
import { INJECT_HEADER, generateInjectsFrom, plural } from './inject.js';
import { recordOutputs } from './outputs.js';

export interface WatchProjectOptions {
  /** Path to tsconfig.json. */
  readonly project: string;
  /** Emit JavaScript and report type errors, like `tsc --watch`. Default true. */
  readonly emit?: boolean;
  /** Regenerate this `avi client` file after every build, writing it only when routes changed. */
  readonly client?: { readonly out: string; readonly root?: string | undefined };
  /** Regenerate this `avi inject` file after every build, writing it only when lists changed. */
  readonly inject?: { readonly out: string };
  /**
   * Called after every build with its error count: type errors and generation errors, or only
   * the latter without emit.
   */
  readonly onBuild?: (errors: number) => void;
}

export interface ProjectWatcher {
  close(): void;
}

/**
 * Watches a TypeScript project, like `tsc --watch`, and keeps the generated files in step with
 * the code. They are generated from the same incremental program, so nothing is parsed twice.
 */
export function watchProject(options: WatchProjectOptions): ProjectWatcher {
  const emit = options.emit ?? true;
  // What each build emits goes on avi build's list, so it can remove outputs of deleted files.
  const projectDir = path.dirname(path.resolve(options.project));
  const emitted = new Set<string>();
  const system: ts.System = {
    ...ts.sys,
    writeFile: (file, text, bom) => {
      ts.sys.writeFile(file, text, bom);
      emitted.add(path.resolve(file));
    },
  };
  const host = ts.createWatchCompilerHost(
    path.resolve(options.project),
    emit ? { preserveWatchOutput: true } : { noEmit: true },
    system,
    ts.createEmitAndSemanticDiagnosticsBuilderProgram,
    undefined,
    // Without emit the only output is the generated files'; tsc's status lines would be noise.
    emit ? undefined : () => undefined,
  );

  let generatedErrors = 0;
  // A file event can still start a build after close(); it must not write or report.
  let closed = false;
  const status = host.onWatchStatusChange?.bind(host);
  host.onWatchStatusChange = (diagnostic, newLine, compilerOptions, errorCount) => {
    if (closed) return;
    status?.(diagnostic, newLine, compilerOptions, errorCount);
    if (errorCount !== undefined) options.onBuild?.(errorCount + generatedErrors);
  };

  const writers = generatedWriters(options);
  const build = host.afterProgramCreate?.bind(host);
  host.afterProgramCreate = (builder) => {
    if (closed) return;
    const program = builder.getProgram();
    const results = writers.map((writer) => ({ out: writer.out, ...writer.write(program) }));
    generatedErrors = results.reduce((sum, result) => sum + result.errors, 0);
    if (!emit) {
      options.onBuild?.(generatedErrors);
      return;
    }
    // Writing a file the program compiles starts another build at once; this one would only
    // report its stale errors. A file outside the program starts nothing, so build now.
    if (results.some((result) => result.written && program.getSourceFile(result.out))) return;
    build?.(builder);
    if (emitted.size > 0) {
      recordOutputs(program.getCompilerOptions().outDir, projectDir, emitted);
      emitted.clear();
    }
  };

  const watcher = ts.createWatchProgram(host);
  return {
    close: () => {
      closed = true;
      watcher.close();
    },
  };
}

export interface GeneratedWrite {
  readonly written: boolean;
  readonly errors: number;
}

/** How every file `avi client` writes begins. */
export const GENERATED = '// Generated by `avi client`';

/** The writers for the generated files `options` asks for. */
export function generatedWriters(options: Pick<WatchProjectOptions, 'client' | 'inject'>) {
  const writers: { out: string; write: (program: ts.Program) => GeneratedWrite }[] = [];
  if (options.client) {
    const { out, root } = options.client;
    writers.push({ out: path.resolve(out), write: clientWriter(out, root) });
  }
  if (options.inject) {
    const { out } = options.inject;
    writers.push({ out: path.resolve(out), write: injectWriter(out) });
  }
  return writers;
}

export function clientWriter(out: string, root: string | undefined) {
  return fileWriter(out, GENERATED, (program, roots, file) => {
    const result = generateFrom(program, roots, { out: file, root });
    return { ...result, summary: `${String(result.routes.length)} routes` };
  });
}

export function injectWriter(out: string) {
  return fileWriter(out, INJECT_HEADER, (program, roots, file) => {
    const result = generateInjectsFrom(program, roots, { out: file });
    return { ...result, summary: plural(result.classes.length, 'dependency list') };
  });
}

type Generate = (
  program: ts.Program,
  roots: ReadonlySet<string>,
  file: string,
) => { source: string; diagnostics: readonly Diagnostic[]; summary: string };

/** Writes a generated file when its content changed, never over a file it did not generate. */
function fileWriter(out: string, header: string, generate: Generate) {
  const file = path.resolve(out);
  let reported = '';
  return (program: ts.Program): GeneratedWrite => {
    const roots = new Set(program.getRootFileNames().map((name) => path.resolve(name)));
    const result = generate(program, roots, file);
    const lines = result.diagnostics.map(formatDiagnostic);
    let errors = result.diagnostics.filter((d) => d.severity === 'error').length;

    let current: string | undefined;
    try {
      current = readFileSync(file, 'utf8');
    } catch {
      current = undefined;
    }
    // A mistyped --out must not replace source code.
    if (current !== undefined && !current.startsWith(header)) {
      lines.push(`${out}: not written: the file exists and was not generated by avi`);
      errors++;
    }

    // Repeat diagnostics only when they change, not on every save.
    const report = lines.join('\n');
    if (report !== reported && report) console.log(report);
    reported = report;
    if (errors > 0) return { written: false, errors };

    if (current !== undefined && sameContent(current, result.source)) {
      return { written: false, errors: 0 };
    }
    mkdirSync(path.dirname(file), { recursive: true });
    writeFileSync(file, result.source);
    console.log(`${out} updated: ${result.summary}`);
    return { written: true, errors: 0 };
  };
}
