import { SYNTAX, VALIDATOR_VERSIONS, type SchemaSyntax, type Validator } from './validators.js';

export type TemplateName = 'modular' | 'minimal';

export interface TemplateOptions {
  name: string;
  template: TemplateName;
  /** Version range for the @avijs packages. */
  aviVersion: string;
  /**
   * Local package files to use instead of the registry, keyed by package name, such as
   * 'file:../artifacts/avijs-core-0.1.0.tgz'. Also added as npm overrides so packages that depend on
   * each other resolve locally too.
   */
  localPackages?: Readonly<Record<string, string>>;
  /** How the users routes validate input. Default: `valibot`. */
  validator?: Validator;
}

/** Every file of a new project, keyed by its path relative to the project folder. */
export function templateFiles(options: TemplateOptions): Record<string, string> {
  const validator = options.validator ?? 'valibot';
  const syntax = validator === 'none' ? undefined : SYNTAX[validator];
  const files = options.template === 'modular' ? modular() : minimal();
  if (syntax) {
    Object.assign(
      files,
      options.template === 'modular' ? modularSchemas(syntax) : minimalSchemas(syntax),
    );
    if (options.template === 'modular') delete files['src/modules/users/dto/create-user.dto.ts'];
  }
  return { ...shared(options, validator), ...files };
}

function shared(
  { name, template, aviVersion, localPackages }: TemplateOptions,
  validator: Validator,
): Record<string, string> {
  const spec = (pkg: string) => localPackages?.[pkg] ?? aviVersion;
  const pkg = {
    name,
    version: '0.1.0',
    private: true,
    type: 'module',
    scripts: {
      build: 'avi build',
      start: 'node dist/main.js',
      dev: 'avi dev',
      check: 'avi check',
      client: 'avi client',
      test: 'avi build && node --test "dist/**/*.test.js"',
    },
    dependencies: {
      '@avijs/core': spec('@avijs/core'),
      ...(validator === 'none' ? {} : { [validator]: VALIDATOR_VERSIONS[validator] }),
    },
    devDependencies: {
      '@avijs/cli': spec('@avijs/cli'),
      '@avijs/testing': spec('@avijs/testing'),
      '@types/node': '^22.0.0',
      typescript: '~6.0.3',
    },
    engines: { node: '>=22.12' },
    ...(localPackages ? { overrides: localPackages } : {}),
  };
  const tsconfig = {
    compilerOptions: {
      target: 'ES2023',
      lib: ['ES2023', 'ESNext.Disposable'],
      module: 'NodeNext',
      moduleResolution: 'NodeNext',
      types: ['node'],
      strict: true,
      skipLibCheck: true,
      outDir: 'dist',
      rootDir: 'src',
      sourceMap: true,
      declaration: true,
    },
    include: ['src'],
  };
  return {
    'package.json': `${JSON.stringify(pkg, null, 2)}\n`,
    'tsconfig.json': `${JSON.stringify(tsconfig, null, 2)}\n`,
    '.gitignore': 'node_modules/\ndist/\n.env\n',
    'README.md': `# ${name}

An [Avi.js](https://github.com/chrischase011/avi-js) API (${template} template).

\`\`\`sh
npm install
npm run dev     # compile and restart on change
npm test        # compile and run the tests
npm start       # run the compiled app
npm run client  # update src/api.gen.ts, the typed API for @avijs/client (avi dev does it on save)
\`\`\`

Then open http://localhost:3000/health and http://localhost:3000/users.
`,
  };
}

/** What `avi client` writes for a template; a CLI test checks they match. */
function apiFile(imports: [string, string, string][], routes: string[]): string {
  return [
    '// Generated by `avi client`; `avi dev` keeps it up to date. Do not edit.',
    `import type { ${imports[0]?.[0] ?? ''} } from '@avijs/core';`,
    ...imports.map(([, name, from]) => `import type { ${name} } from '${from}';`),
    '',
    'export interface Api {',
    ...routes.map((route) => `  ${route};`),
    '}',
    '',
  ].join('\n');
}

const MAIN_LISTEN = listenOn("Number(process.env['PORT'] ?? 3000)");

function listenOn(port: string): string {
  return `await app.listen(${port});

const shutdown = () => {
  void app.close().then(() => process.exit(0));
};
process.once('SIGINT', shutdown);
process.once('SIGTERM', shutdown);
`;
}

/** `src/config.ts`: environment variables checked at startup. */
function configFile(syntax: SchemaSyntax): string {
  return `import { defineConfig, type TokenType } from '@avijs/core';
${syntax.import}

// Environment variables, checked when the app starts. A .env file is read too, if present.
const env = ${syntax.object([['PORT', syntax.port]])};

export const Config = defineConfig(env, { envFile: '.env' });
// The validated values, to type an injected config: constructor(private readonly config: Config).
export type Config = TokenType<typeof Config>;
`;
}

